# 语言 -> 词典
TRANSLATIONS = {
    "en_US": _EN,
    "zh_CN": {},   # 中文即 key, 无需翻译
}


def tr(text: str) -> str:
    """翻译文案: 按当前语言查词典, 未命中或中文时原样返回"""
    if not text:
        return text
    try:
        from app.core.ui_settings import UISettings
        lang = UISettings.instance().language
    except Exception:
        lang = "zh_CN"
    table = TRANSLATIONS.get(lang)
    if not table:
        return text
    return table.get(text, text)
